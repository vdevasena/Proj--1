# 📄 Example data for compare_df
compare_df = pd.DataFrame({
    "AccountName": ["Acme Incorporated", "Beta Sys GmbH", "Zen Sol","BOFA"],
    "Website": ["acmeinc.com", "beta-systems.de", "zen-solutions.com","bankofmaerica.com"],
    "City": ["NYC", "Berlin", "Austin","New York"],
    "Country": ["United States", "Germany", "United States","USA"]})

# Combine fields into a single string for embedding
main_df["combined"] = main_df[["CleanAccountName", "CleanWebsite", "CleanCity", "CleanCountry"]].fillna("").agg(" ".join, axis=1)
compare_df["combined"] = compare_df[["AccountName", "Website", "City", "Country"]].fillna("").agg(" ".join, axis=1)

# Function to get embeddings from OpenAI
def get_embedding(text, model="text-embedding-3-small"):
    response = openai.embeddings.create(input=[text], model=model)
    return response.data[0].embedding

# Get embeddings with throttling
def get_all_embeddings(texts, delay=1):
    embeddings = []
    for text in texts:
        try:
            emb = get_embedding(text)
            embeddings.append(emb)
            time.sleep(delay)  # Be nice to the API
        except Exception as e:
            print(f"Error for text '{text}': {e}")
            embeddings.append([0]*1536)  # Fallback vector size
    return embeddings

# Get embeddings for both sets
main_embeddings = get_all_embeddings(main_df["combined"].tolist())
compare_embeddings = get_all_embeddings(compare_df["combined"].tolist())

# Convert to numpy arrays
main_embeddings = np.array(main_embeddings)
compare_embeddings = np.array(compare_embeddings)

# Calculate cosine similarity
similarity_matrix = cosine_similarity(main_embeddings, compare_embeddings)

# Find best match for each row in main_df
top_matches = []
for i, row_sim in enumerate(similarity_matrix):
    best_idx = np.argmax(row_sim)
    score = row_sim[best_idx]
    top_matches.append({
        "main_record": main_df.iloc[i]["combined"],
        "matched_with": compare_df.iloc[best_idx]["combined"],
        "similarity_score": round(score, 4)
    })

# Convert to DataFrame and display
match_df = pd.DataFrame(top_matches)
print(match_df.sort_values("similarity_score", ascending=False).head(10))

