import pandas as pd
from sentence_transformers import SentenceTransformer
from sklearn.metrics.pairwise import cosine_similarity

# Load CSVs

# 📄 Example data for main_df
main_df = pd.DataFrame({
    "CleanAccountName": ["Acme Corp", "Beta Systems", "Zen Solutions","Bank Of America"],
    "CleanWebsite": ["acme.com", "betasys.de", "zensol.com","bofa.com"],
    "CleanCity": ["New York", "Berlin", "Austin","New York"],
    "CleanCountry": ["USA", "Germany", "USA","USA"]
})

# 📄 Example data for compare_df
compare_df = pd.DataFrame({
    "AccountName": ["Acme Ventures", "Systems GmbH", "Zen Sol","BOFA"],
    "Website": ["acmeinc.com", "beta-systems.de", "zen-solutions.com","bankofamerica.com"],
    "City": ["NYC", "Berlin", "Austin","New York"],
    "Country": ["United States", "Germany", "United States","USA"]})

# Combine fields into a single string for similarity matching
main_df["combined"] = main_df[['CleanAccountName', 'CleanWebsite', 'CleanCity', 'CleanCountry']].fillna('').agg(' '.join, axis=1)
compare_df["combined"] = compare_df[['AccountName', 'Website', 'City', 'Country']].fillna('').agg(' '.join, axis=1)

# Load LLM model for embeddings
model = SentenceTransformer('all-MiniLM-L6-v2')  # Fast and good

# Encode embeddings
main_embeddings = model.encode(main_df["combined"].tolist(), convert_to_tensor=True).cpu() # Move tensor to CPU
compare_embeddings = model.encode(compare_df["combined"].tolist(), convert_to_tensor=True).cpu() # Move tensor to CPU


# Compute cosine similarity
similarity_scores = cosine_similarity(main_embeddings, compare_embeddings)

# Get top matches
top_matches = []
for i, row in enumerate(similarity_scores):
    best_match_idx = row.argmax()
    score = row[best_match_idx]
    top_matches.append({
        "main_record": main_df.iloc[i]["combined"],
        "matched_with": compare_df.iloc[best_match_idx]["combined"],
        "similarity_score": score
    })

# Convert to DataFrame
matches_df = pd.DataFrame(top_matches)
matches_df = matches_df.sort_values(by="similarity_score", ascending=False)

# View results
print(matches_df.head(10))

